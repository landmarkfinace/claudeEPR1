// Generate src/lib/agreement-fonts.ts — embeds the EXACT Google-Fonts webfonts
// the bilingual agreement template declares ("Noto Naskh Arabic" + "Noto Sans")
// as data-URL @font-face rules, so the sheet renders identically in the app
// preview, window.print() and the server print daemon (no network at render
// time, Arabic shaping + RTL guaranteed by real Naskh glyphs).
//
// Also writes /home/z/my-project/scripts/agr-reference.html — the ORIGINAL
// uploaded agreement-template.html with its Google Fonts <link> swapped for the
// same inline @font-face CSS, used as the reference render for PDF comparison.
//
// Keep: Noto Naskh Arabic — ALL subsets; Noto Sans — latin + latin-ext only
// (the document's Latin text; upright 400..700 variable, one file per subset).
import fs from 'node:fs'

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Noto+Naskh+Arabic:wght@400..700&family=Noto+Sans:wght@400..700&display=swap'
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
const OUT_TS = new URL('../src/lib/agreement-fonts.ts', import.meta.url).pathname
const OUT_REF = '/home/z/my-project/scripts/agr-reference.html'
const SRC_TEMPLATE = '/home/z/my-project/upload/agreement-template.html'

const css = await fetch(CSS_URL, { headers: { 'User-Agent': UA } }).then((r) => {
  if (!r.ok) throw new Error(`css2 HTTP ${r.status}`)
  return r.text()
})

// Split into "/* subset */\n@font-face {...}" blocks (order preserved).
const blocks = []
const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g
for (const m of css.matchAll(re)) {
  blocks.push({ subset: m[1], face: m[2] })
}
if (blocks.length === 0) throw new Error('no @font-face blocks parsed')

const keep = (family, subset) =>
  family === 'Noto Naskh Arabic' || (family === 'Noto Sans' && (subset === 'latin' || subset === 'latin-ext'))

const outFaces = []
let totalWoff2 = 0
for (const b of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(b.face)?.[1]
  if (!family) continue
  if (!keep(family, b.subset)) continue
  const url = /src:\s*url\(([^)]+)\)/.exec(b.face)?.[1]
  if (!url) continue
  const buf = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } }).then((r) => {
    if (!r.ok) throw new Error(`woff2 HTTP ${r.status} for ${url}`)
    return r.arrayBuffer()
  }))
  totalWoff2 += buf.length
  const dataUrl = `data:font/woff2;base64,${buf.toString('base64')}`
  const inlined = b.face.replace(/src:\s*url\([^)]+\)\s*format\('woff2'\)/, `src: url(${dataUrl}) format('woff2')`)
  if (inlined === b.face) throw new Error(`src swap failed for ${family} ${b.subset}`)
  outFaces.push(`/* ${b.subset} */\n${inlined}`)
  console.log(`embedded ${family} / ${b.subset} — ${(buf.length / 1024).toFixed(1)} KB woff2`)
}

const ts = `// AUTO-GENERATED by scripts/agr-make-fonts.mjs — DO NOT EDIT BY HAND.
// The agreement template's Google webfonts ("Noto Naskh Arabic" + "Noto Sans",
// 400..700 variable, per-subset unicode-range exactly as Google serves them)
// inlined as data-URL @font-face rules. Self-contained: renders identically in
// the app, window.print() and the headless render daemon with no network.
export const AGREEMENT_FONT_FACES_CSS = ${JSON.stringify(outFaces.join('\n'))}
`
fs.writeFileSync(OUT_TS, ts)
console.log(`\nwrote ${OUT_TS} (${(ts.length / 1024).toFixed(1)} KB, ${(totalWoff2 / 1024).toFixed(1)} KB woff2)`)

// Reference render: original template file with fonts inlined (everything else
// byte-identical to the uploaded file).
const template = fs.readFileSync(SRC_TEMPLATE, 'utf8')
const linkRe = /<link rel="preconnect"[^>]*>\s*<link rel="preconnect"[^>]*>\s*<link href="https:\/\/fonts\.googleapis\.com\/[^"]*" rel="stylesheet">/
if (!linkRe.test(template)) throw new Error('Google Fonts <link> block not found in the uploaded template')
const fontsStyle = outFaces.join('\n')
const reference = template.replace(
  linkRe,
  `<style>\n/* Fonts inlined (generated) — replaces the Google Fonts <link> so the reference renders offline */\n${fontsStyle}\n</style>`
)
fs.writeFileSync(OUT_REF, reference)
console.log(`wrote ${OUT_REF} (${(reference.length / 1024).toFixed(1)} KB)`)
